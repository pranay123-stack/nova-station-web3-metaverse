#!/usr/bin/env node
/**
 * Extracts ABIs from the Foundry build output into typed TypeScript modules
 * under packages/shared/src/contracts.
 *
 * Keeping the ABI in the repo (rather than reading `out/` at runtime) means the
 * web and server builds do not depend on Foundry being installed, and a stale
 * ABI shows up as a git diff rather than as a mystery runtime error.
 */
import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const outDir = join(root, 'contracts', 'out');
const targetDir = join(root, 'packages', 'shared', 'src', 'contracts');

const CONTRACTS = ['NovaAssets', 'NovaItems', 'NovaMarketplace', 'NovaRewardVault'];

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  if (!(await exists(outDir))) {
    console.warn(
      '[export-abi] contracts/out not found — run `pnpm --filter @nova/contracts build` first. Keeping existing ABIs.',
    );
    return;
  }

  await mkdir(targetDir, { recursive: true });
  const written = [];

  for (const name of CONTRACTS) {
    const artifactPath = join(outDir, `${name}.sol`, `${name}.json`);
    if (!(await exists(artifactPath))) {
      console.warn(`[export-abi] missing artifact for ${name}, skipping`);
      continue;
    }
    const artifact = JSON.parse(await readFile(artifactPath, 'utf8'));
    const abi = artifact.abi ?? [];
    const body = `// AUTO-GENERATED by scripts/export-contract-artifacts.mjs — do not edit by hand.
// Source: contracts/src/${name}.sol

export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;
`;
    await writeFile(join(targetDir, `${name}.ts`), body, 'utf8');
    written.push(name);
  }

  const index = `// AUTO-GENERATED by scripts/export-contract-artifacts.mjs — do not edit by hand.
${written.map((n) => `export { ${n}Abi } from './${n}.js';`).join('\n')}
`;
  await writeFile(join(targetDir, 'index.ts'), index, 'utf8');
  console.log(`[export-abi] wrote ${written.length} ABIs to packages/shared/src/contracts`);
}

main().catch((error) => {
  console.error('[export-abi] failed:', error);
  process.exitCode = 1;
});
